    icon = QImage(os.path.join(ROOT, "branding", "icons", "png", "suite_256.png"))
    for scale, name in ((1, "wizard.bmp"), (2, "wizard@2x.bmp")):
        w, h = 164 * scale, 314 * scale
        img = QImage(w, h, QImage.Format_RGB32)
        p = QPainter(img)
        g = QLinearGradient(0, 0, 0, h)
        g.setColorAt(0, QColor("#3E9142"))
        g.setColorAt(1, QColor("#1B5E20"))
        p.fillRect(img.rect(), g)
        p.setRenderHint(QPainter.SmoothPixmapTransform)
        p.drawImage(QRectF(w * 0.17, h * 0.16, w * 0.66, w * 0.66), icon)
        p.setPen(QColor("white"))
        f = QFont("Segoe UI", 15 * scale, QFont.Bold)
        p.setFont(f)
        p.drawText(QRectF(0, h * 0.58, w, 30 * scale), Qt.AlignHCenter, "EthicalApp")
        f.setPointSize(8 * scale)
        f.setBold(False)
        p.setFont(f)
        p.drawText(QRectF(10 * scale, h * 0.68, w - 20 * scale, 60 * scale), Qt.AlignHCenter | Qt.TextWordWrap,
                   "Free office, PDF, photo, convert & database apps")
        p.end()
        img.save(os.path.join(BUILD, name))
    for scale, name in ((1, "small.bmp"), (2, "small@2x.bmp")):
        s = 55 * scale
        img = QImage(s, s, QImage.Format_RGB32)
        img.fill(QColor("white"))
        p = QPainter(img)
        p.setRenderHint(QPainter.SmoothPixmapTransform)
        p.drawImage(QRectF(0, 0, s, s), icon)
        p.end()
        img.save(os.path.join(BUILD, name))



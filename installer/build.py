def copy_extras():
    # helpers used by the converter
    import imageio_ffmpeg
    os.makedirs(os.path.join(OUT, "ffmpeg"), exist_ok=True)
    shutil.copy2(imageio_ffmpeg.get_ffmpeg_exe(), os.path.join(OUT, "ffmpeg", "ffmpeg.exe"))
    shutil.rmtree(os.path.join(OUT, "deno"), ignore_errors=True)
    try:
        if not WITH_DOWNLOADER:
            raise RuntimeError("public build - downloader left out")
        import deno
        os.makedirs(os.path.join(OUT, "deno"), exist_ok=True)
        shutil.copy2(deno.find_deno_bin(), os.path.join(OUT, "deno", "deno.exe"))
    except Exception as ex:
        print("deno not bundled:", ex)
    # guide + icons (same folder layout as the source tree, so the code finds them)
    for sub in ("guide", os.path.join("branding", "icons"), os.path.join("branding", "sounds")):
        dst = os.path.join(OUT, sub)
        shutil.rmtree(dst, ignore_errors=True)
        shutil.copytree(os.path.join(ROOT, sub), dst)
    # source code (the suite is open source; licences of PyMuPDF/FFmpeg require offering it)
    src = os.path.join(OUT, "source")
    shutil.rmtree(src, ignore_errors=True)
    shutil.copytree(APPS_DIR, os.path.join(src, "apps"), ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    shutil.copytree(os.path.join(ROOT, "installer"), os.path.join(src, "installer"),
                    ignore=shutil.ignore_patterns("__pycache__", "*.bmp", "EthicalSuite.iss"))   # .iss is generated (has local paths)
    os.makedirs(os.path.join(src, "branding"), exist_ok=True)
    shutil.copy2(os.path.join(ROOT, "branding", "make_icons.py"), os.path.join(src, "branding"))
    for f in ("LICENSE", "README.md", "requirements.txt", "setup.bat"):      # (PROGRESS/CLAUDE/RELEASE.md are private notes)
        shutil.copy2(os.path.join(ROOT, f), src)
    shutil.copytree(os.path.join(ROOT, "licenses"), os.path.join(src, "licenses"))
    write_licenses()



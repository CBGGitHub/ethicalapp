def build_programs():
    os.makedirs(BUILD, exist_ok=True)
    v = ", ".join(VERSION.split("."))
    with open(os.path.join(BUILD, "version.txt"), "w", encoding="utf-8") as fh:
        fh.write(VERSION_INFO.format(v=v, s=VERSION))
    spec = f"WITH_DOWNLOADER = {WITH_DOWNLOADER}\n" + SPEC.replace("APPS_DIR", APPS_DIR).replace("ROOT", ROOT).replace("BUILD", BUILD)
    spec_path = os.path.join(BUILD, "EthicalSuite.spec")
    with open(spec_path, "w", encoding="utf-8") as fh:
        fh.write(spec)
    run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
         "--distpath", DIST, "--workpath", os.path.join(BUILD, "work"), spec_path])


